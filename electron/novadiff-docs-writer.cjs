"use strict";

const fs = require("node:fs/promises");
const path = require("node:path");

const NOVADIFF_DOCS = "novadiff-docs";
const DEFAULT_BUNDLE_KEY = "change-report";

function bundleKeyOf(bundle) {
  const raw = String(bundle?.bundleKey ?? bundle?.docMode ?? DEFAULT_BUNDLE_KEY).trim();
  return raw || DEFAULT_BUNDLE_KEY;
}

function bundleBaseDir(root, bundle) {
  return path.join(root, NOVADIFF_DOCS, bundleKeyOf(bundle));
}

function bundleHeadline(bundle) {
  switch (bundleKeyOf(bundle)) {
    case "codebase-baseline":
      return "NovaDiff baseline codebase bundle";
    case "codebase-target":
      return "NovaDiff target codebase bundle";
    default:
      return "NovaDiff change report bundle";
  }
}

/**
 * @param {object} bundle
 * @param {string} bundle.targetRoot
 * @param {string} [bundle.leftRoot]
 * @param {string} [bundle.rightRoot]
 * @param {string} [bundle.leftTitle]
 * @param {string} [bundle.rightTitle]
 * @param {string} [bundle.generatedAt]
 * @param {string} [bundle.aiMarkdown]
 * @param {string} [bundle.compareMetricsMd]
 * @param {unknown} [bundle.codebaseOutline]
 * @param {string} [bundle.changeMixMermaid]
 * @param {string} [bundle.depthMermaid]
 * @param {string} [bundle.importGraphMermaid]
 * @param {string} [bundle.crossFileCallGraphMermaid]
 * @param {string} [bundle.classDiagramMermaid]
 * @param {object[]} [bundle.riskSignals]
 * @param {object[]} [bundle.summaryIndex]
 * @param {object[]} [bundle.selectionIndex]
 * @param {string} [bundle.releaseOverviewMd]
 * @param {object[]} [bundle.confidenceBadges]
 */
function readme(bundle) {
  const rt = bundle.rightTitle || "Target";
  const lt = bundle.leftTitle || "Baseline";
  const bundleKey = bundleKeyOf(bundle);
  return [
    `# ${bundleHeadline(bundle)}`,
    "",
    "This folder is **generated by NovaDiff**. Paths here are excluded from folder",
    "compare, prefetch summaries, per-file LLM summaries, and documentation workspace",
    "metrics so generated docs are not fed back into the model.",
    "",
    `**Bundle key:** \`${bundleKey}\``,
    "",
    "## Contents",
    "",
    "| File | Purpose |",
    "| --- | --- |",
    "| `AI_PROJECT_DOC.md` | Streaming Markdown narrative for this bundle |",
    "| `COMPARE_METRICS.md` | Metrics or structural summary Markdown for this bundle |",
    "| `codebase-outline.json` | Heuristic scan used to generate this bundle |",
    "| `diagrams/*.mmd` | Mermaid sources for this bundle's charts and graphs |",
    "| `NovaDiff-Documentation.pdf` | Full PDF export for this bundle |",
    "| `NovaDiff-Diagrams.pdf` | Diagram pack PDF for this bundle |",
    "| `summaries/<relative path>/summary.html` | Per-file LLM summary (prefetch or manual) as HTML; Mermaid fences render when online |",
    "| `summaries/<relative path>/summary.pdf` | Same summary as a printable PDF |",
    "| `summaries/_by-hash/<sha256>/` | Fallback folder when the relative path is unsafe or too long for the filesystem |",
    "| `narrative.html` | AI narrative as HTML; Mermaid fences render interactively (CDN) |",
    "| `metrics.html` | Compare metrics as HTML |",
    "| `diagrams.html` | Diagram pack as HTML with live Mermaid |",
    "| `release.html` | Release / PR rollup with searchable summaries and deterministic risk signals |",
    "| `index.html` | Overview hub with links to the HTML report pages |",
    "| `risk-signals.json` | Deterministic heuristic risk signals emitted for this bundle |",
    "| `summary-index.json` | Saved per-file summary index used for release rollups and drill-downs |",
    "| `selection-index.json` | Saved selected-diff documentation index |",
    "| `RELEASE_OVERVIEW.md` | PR-ready rollup Markdown for this bundle |",
    "",
    `**Target:** ${rt} — \`${bundle.rightRoot || ""}\``,
    "",
    `**Baseline:** ${lt} — \`${bundle.leftRoot || ""}\``,
    "",
    `**Generated:** ${bundle.generatedAt || new Date().toISOString()}`,
    "",
  ].join("\n");
}

async function writeNovadiffDocsBundle(bundle) {
  const root = bundle?.targetRoot?.trim?.();
  if (!root) {
    throw new Error("Missing targetRoot");
  }
  const base = bundleBaseDir(root, bundle);
  const diagrams = path.join(base, "diagrams");
  await fs.mkdir(diagrams, { recursive: true });

  await fs.writeFile(path.join(base, "README.md"), readme(bundle), "utf8");
  await fs.writeFile(
    path.join(base, "AI_PROJECT_DOC.md"),
    String(bundle.aiMarkdown ?? ""),
    "utf8",
  );
  await fs.writeFile(
    path.join(base, "COMPARE_METRICS.md"),
    String(bundle.compareMetricsMd ?? ""),
    "utf8",
  );
  await fs.writeFile(
    path.join(base, "codebase-outline.json"),
    JSON.stringify(bundle.codebaseOutline ?? {}, null, 2),
    "utf8",
  );
  await fs.writeFile(
    path.join(base, "risk-signals.json"),
    JSON.stringify(bundle.riskSignals ?? [], null, 2),
    "utf8",
  );
  await fs.writeFile(
    path.join(base, "summary-index.json"),
    JSON.stringify(bundle.summaryIndex ?? [], null, 2),
    "utf8",
  );
  await fs.writeFile(
    path.join(base, "selection-index.json"),
    JSON.stringify(bundle.selectionIndex ?? [], null, 2),
    "utf8",
  );
  await fs.writeFile(
    path.join(base, "confidence-badges.json"),
    JSON.stringify(bundle.confidenceBadges ?? [], null, 2),
    "utf8",
  );
  await fs.writeFile(
    path.join(base, "RELEASE_OVERVIEW.md"),
    String(bundle.releaseOverviewMd ?? ""),
    "utf8",
  );

  await fs.writeFile(
    path.join(diagrams, "change-mix.mmd"),
    String(bundle.changeMixMermaid ?? ""),
    "utf8",
  );
  await fs.writeFile(
    path.join(diagrams, "depth-distribution.mmd"),
    String(bundle.depthMermaid ?? ""),
    "utf8",
  );
  await fs.writeFile(
    path.join(diagrams, "module-imports.mmd"),
    String(bundle.importGraphMermaid ?? ""),
    "utf8",
  );
  await fs.writeFile(
    path.join(diagrams, "cross-file-calls.mmd"),
    String(bundle.crossFileCallGraphMermaid ?? ""),
    "utf8",
  );
  await fs.writeFile(
    path.join(diagrams, "types-classes.mmd"),
    String(bundle.classDiagramMermaid ?? ""),
    "utf8",
  );

  return { ok: true, dir: base, bundleKey: bundleKeyOf(bundle) };
}

module.exports = { writeNovadiffDocsBundle, NOVADIFF_DOCS };
